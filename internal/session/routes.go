package session

import "net/http"

func (s *Service) RegisterRoutes(mux *http.ServeMux) {
	mux.HandleFunc("GET /api/sessions", s.SessionsHandler)
	mux.HandleFunc("GET /api/sessions/{session}/image", s.SessionImageHandler)
	mux.HandleFunc("GET /api/conversation-drafts", s.DraftHandler)
	mux.HandleFunc("POST /api/conversation-drafts", s.DraftHandler)
	mux.HandleFunc("GET /api/codex/chat-options", s.ChatOptionsHandler)
	mux.HandleFunc("GET /api/sessions/{session}/context", s.ChatContextHandler)
	mux.HandleFunc("POST /api/sessions/{session}/manage", s.ManageSessionHandler)
	mux.HandleFunc("POST /api/sessions/{session}/chat/steer", s.ChatSteerHandler)
	mux.HandleFunc("POST /api/sessions/new", s.NewSessionHandler)
	mux.HandleFunc("POST /api/sessions/{session}/resume", s.ResumeSessionHandler)
	mux.HandleFunc("GET /api/sessions/{session}/history", s.SessionHistoryHandler)
	mux.HandleFunc("GET /api/sessions/{session}/history/events", s.SessionHistoryEventsHandler)
	mux.HandleFunc("GET /api/sessions/{session}/chat", s.ChatStateHandler)
	mux.HandleFunc("POST /api/sessions/{session}/chat", s.ChatStartHandler)
	mux.HandleFunc("GET /api/sessions/{session}/chat/events", s.ChatEventsHandler)
	mux.HandleFunc("POST /api/sessions/{session}/chat/stop", s.ChatStopHandler)
	mux.HandleFunc("POST /api/sessions/{session}/chat/approval", s.ChatApprovalHandler)
	mux.HandleFunc("POST /api/sessions/{session}/chat/approval/open", s.ChatApprovalOpenHandler)
	mux.HandleFunc("POST /api/sessions/{session}/chat/handoff", s.ChatHandoffHandler)
	mux.HandleFunc("POST /api/requirements/{id}/launch", s.LaunchHandler)
	mux.HandleFunc("POST /api/requirements/{id}/merge-ai", s.MergeAIHandler)
	mux.HandleFunc("GET /api/codex/sessions", s.CodexSessionsHandler)
	mux.HandleFunc("GET /api/requirements/{id}/sessions", s.RequirementSessionsHandler)
	mux.HandleFunc("POST /api/requirements/{id}/sessions", s.LinkSessionHandler)
	mux.HandleFunc("DELETE /api/requirements/{id}/sessions/{session}", s.UnlinkSessionHandler)
	mux.HandleFunc("POST /api/requirements/{id}/sessions/new", s.NewSessionHandler)
	mux.HandleFunc("POST /api/requirements/{id}/sessions/{session}/resume", s.taskSessionAdapter(s.ResumeSessionHandler, true))
	mux.HandleFunc("GET /api/requirements/{id}/sessions/{session}/history", s.taskSessionAdapter(s.SessionHistoryHandler, false))
	mux.HandleFunc("GET /api/requirements/{id}/sessions/{session}/history/events", s.taskSessionAdapter(s.SessionHistoryEventsHandler, false))
	mux.HandleFunc("GET /api/requirements/{id}/sessions/{session}/chat", s.taskSessionAdapter(s.ChatStateHandler, false))
	mux.HandleFunc("POST /api/requirements/{id}/sessions/{session}/chat", s.taskSessionAdapter(s.ChatStartHandler, true))
	mux.HandleFunc("GET /api/requirements/{id}/sessions/{session}/chat/events", s.taskSessionAdapter(s.ChatEventsHandler, false))
	mux.HandleFunc("POST /api/requirements/{id}/sessions/{session}/chat/stop", s.taskSessionAdapter(s.ChatStopHandler, false))
	mux.HandleFunc("POST /api/requirements/{id}/sessions/{session}/chat/approval", s.taskSessionAdapter(s.ChatApprovalHandler, false))
	mux.HandleFunc("POST /api/requirements/{id}/sessions/{session}/chat/approval/open", s.taskSessionAdapter(s.ChatApprovalOpenHandler, false))
	mux.HandleFunc("POST /api/requirements/{id}/sessions/{session}/chat/handoff", s.taskSessionAdapter(s.ChatHandoffHandler, true))
}
